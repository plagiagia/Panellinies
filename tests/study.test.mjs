import assert from 'node:assert/strict';
import { topics } from '../src/topics-data.ts';
import { topicGroups } from '../src/topic-groups.ts';
import { readStudy, writeStudy, studyKey } from '../src/study-state.ts';
const values = new Map();
globalThis.localStorage = { getItem: key => values.get(key), setItem: (key, value) => values.set(key, value) };
globalThis.window = { dispatchEvent() {} };
const key = studyKey('math-2025', 'a1');
assert.equal(readStudy(key).done, false);
const entry = { done: true, saved: true, note: 'A personal note', highlights: [{ start: 2, end: 6, text: 'word', color: 'green' }] };
assert.equal(writeStudy(key, entry), true);
assert.deepEqual(readStudy(key), entry);
assert.equal(readStudy(studyKey('physics-2025', 'a1')).done, false);
values.set(key, '{broken'); assert.equal(readStudy(key).done, false);
values.set(key, JSON.stringify({ highlights: [null, { start: -1, end: 5 }, { start: 1, end: 2, text: 'a', color: 'red' }] }));
assert.deepEqual(readStudy(key).highlights, []);
localStorage.setItem = () => { throw new Error('Unavailable storage'); };
assert.equal(writeStudy(key, entry), false);
for (const topic of topics) assert.equal(topicGroups.filter(g => g.subject === topic.subject && g.ids.includes(topic.id)).length, 1, `${topic.id} must belong to exactly one group`);
for (const group of topicGroups) for (const id of group.ids) assert.ok(topics.some(t => t.id === id && t.subject === group.subject));
console.log('Validated study persistence, invalid data, storage failure and topic grouping.');
